function areaSquare(side) {
    return side * side;
}

console.log(areaSquare(5)); 

//area ractangulala
function areaRectangle(length, width) {
    return length * width;
}

console.log(areaRectangle(6, 4)); 

//area cycle
function areaCircle(radius) {
    return Math.PI * radius * radius;
}

console.log(areaCircle(3)); 